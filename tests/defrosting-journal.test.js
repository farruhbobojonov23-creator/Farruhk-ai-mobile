import test from 'node:test';
import assert from 'node:assert/strict';
import {emptyHaccp,addJournalRecord,validateHaccp} from '../public/haccp-model.js';
import {defrostingDetails} from '../public/haccp-extra.js';
import {thawConfig,updateThawConfig,thawElapsed} from '../public/thaw-config.js';
import {saveAutoTemplate,dueAutoDrafts} from '../public/haccp-template-drafts.js';
import {automaticJournalRows} from '../public/haccp-auto-journals.js';
import {paperCell,paperColumns} from '../public/haccp-paper-layout.js';

const fixture=()=>({haccp:emptyHaccp()});
const fields={kind:'defrosting',pointId:'point-1',at:'2026-10-22T12:00:00Z',
 owner:'Сушист Иванов',product:'Лосось',batch:'B-15',quantity:'3 кг',
 method:'В холодильнике (+2…+6 °C; если разрешено маркировкой и утверждённой инструкцией)',
 startedAt:'2026-10-21T20:00:00Z',finishedAt:'2026-10-22T08:00:00Z',
 measured:3,chamberTemperature:4,approvedHours:14,
 reviewer:'Старший смены Петров',result:'done'};
test('Standard four branches and approved +2…+6 fridge guidance; no invented hours',()=>{
 const h=emptyHaccp();
 assert.equal(h.points.length,4);
 const config=thawConfig(h,'point-1');
 assert.ok(config.products.includes('Лосось')&&config.products.includes('Креветки'));
 assert.equal(config.executor,'Сушист');
 assert.equal(config.reviewer,'Старший смены');
 assert.equal(config.min,2);assert.equal(config.max,6);
 assert.equal(thawElapsed(fields.startedAt,fields.finishedAt),12);
 assert.ok(!Object.hasOwn(config,'approvedHours'));
});
test('Independent per-point thaw product lists, methods and supervisor',()=>{
 const state=fixture();
 updateThawConfig(state,'point-1',{products:['Лосось'],methods:['Холодильник № 1'],executor:'Сушист',reviewer:'Старший смены'});
 assert.deepEqual(thawConfig(validateHaccp(state.haccp),'point-1').products,['Лосось']);
 assert.ok(thawConfig(state.haccp,'point-2').products.includes('Тунец'));
 assert.deepEqual(thawConfig(state.haccp,'point-1').methods,['Холодильник № 1']);
});
test('Completed defrost is measured, reviewer confirmed, printable and compares approved hours',()=>{
 const state=fixture(),record=addJournalRecord(state,fields);
 assert.equal(record.status,'ok');
 assert.equal(record.details.elapsedHours,12);
 assert.equal(record.details.chamberTemperature,4);
 assert.equal(record.details.reviewer,'Старший смены Петров');
 assert.ok(paperColumns('defrosting').map(x=>x.key).includes('thawDuration'));
 assert.match(paperCell(record,'thawDuration',state.haccp.points),/12 ч/);
 assert.match(paperCell(record,'thawTemperatures',state.haccp.points),/Холодильник: 4/);
});
test('Incomplete record never pretends completion and an unknown legal time is not approved',()=>{
 const state=fixture();
 const started=addJournalRecord(state,{...fields,result:'na',finishedAt:'',measured:'',chamberTemperature:'',reviewer:'',approvedHours:''});
 assert.equal(started.status,'unconfigured');
 assert.equal(started.details.elapsedHours,null);
 const noHours=addJournalRecord(state,{...fields,approvedHours:''});
 assert.equal(noHours.status,'unconfigured');
 assert.throws(()=>addJournalRecord(state,{...fields,finishedAt:''}),/Для завершения/);
 assert.throws(()=>addJournalRecord(state,{...fields,reviewer:''}),/Для завершения/);
 assert.throws(()=>addJournalRecord(state,{...fields,chamberTemperature:''}),/Для завершения/);
});
test('Overdue approved hours or refrigerator out-of-range cannot be signed compliant',()=>{
 const state=fixture();
 assert.throws(()=>addJournalRecord(state,{...fields,approvedHours:10}),/Выбери «Нарушение»/);
 assert.throws(()=>addJournalRecord(state,{...fields,chamberTemperature:7}),/Выбери «Нарушение»/);
 const problem=addJournalRecord(state,{...fields,approvedHours:10,result:'problem',notes:'Изолирован продукт до решения'});
 assert.equal(problem.status,'deviation');
 assert.equal(state.haccp.actions.length,1);
});
test('No daily autogenerated fake thaw entries or completed inspections',()=>{
 const state=fixture();
 state.haccp.dailyControls.push('defrosting');
 assert.throws(()=>saveAutoTemplate(state,{kind:'defrosting',pointId:'point-1',form:{product:'Лосось'}}),/по факту/);
 assert.deepEqual(dueAutoDrafts(state.haccp,new Date('2026-10-22T12:00:00Z')),[]);
 assert.deepEqual(automaticJournalRows(state.haccp,{kind:'defrosting',month:'2026-10',now:new Date('2026-10-22T12:00:00Z')}),[]);
});
