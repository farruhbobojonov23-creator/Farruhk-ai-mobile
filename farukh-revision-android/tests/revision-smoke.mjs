for(const pattern of [/const FARUKH_UI_RELEASE='0\.4\.0'/,/rev040Snapshot/,/rev040Switch/,/downloadPointsSummary/,/onclick="confirmClearDraft\(\)"/,/revision-crimson/]) assert.match(html,pattern);
