/* FARUKH PRINT PRO: privacy-first QR selection.
 * No external barcode services, uploads, or camera recording.
 * BarcodeDetector is a browser capability. Manual code search is the fallback.
 */
(()=>{'use strict';
const $=id=>document.getElementById(id),dialog=$('pro-qr-dialog'),video=$('pro-qr-video');
if(!dialog||!video)return;
let active=false,stream=null,detector=null,timer=null;
const imageBuffer=document.createElement('canvas'),imageContext=imageBuffer.getContext('2d',{willReadFrequently:true});
const note=text=>$('pro-qr-status').textContent=text;
function stop(){
 active=false;clearTimeout(timer);timer=null;
 if(stream){for(const track of stream.getTracks())track.stop();stream=null}
 try{video.pause()}catch{}
 video.srcObject=null;
}
function close(){stop();if(dialog.open)dialog.close()}
function select(raw){
 const api=window.FARUKH_PRINT_PRO_SCAN;
 if(!api){note('Каталог ещё не загрузился.');return false}
 const p=api.find(raw);
 if(!p){note('Товар не найден. Проверь код и обновление каталога.');return false}
 close();
 if(!api.select(p)){note('Не удалось открыть позицию.');return false}
 return true;
}
async function step(){
 if(!active||!dialog.open)return;
 try{
  if(video.readyState>=2){
   if(detector){
    const found=await detector.detect(video);
    if(!active||!dialog.open)return;
    for(const item of found)if(select(String(item.rawValue||'').slice(0,512)))return;
   }else if(typeof window.jsQR==='function'&&imageContext&&video.videoWidth>0){
    const ratio=Math.min(1,640/video.videoWidth);
    imageBuffer.width=Math.max(1,Math.round(video.videoWidth*ratio));
    imageBuffer.height=Math.max(1,Math.round(video.videoHeight*ratio));
    imageContext.drawImage(video,0,0,imageBuffer.width,imageBuffer.height);
    const frame=imageContext.getImageData(0,0,imageBuffer.width,imageBuffer.height);
    const decoded=window.jsQR(frame.data,imageBuffer.width,imageBuffer.height,{inversionAttempts:'dontInvert'});
    if(decoded?.data&&select(decoded.data))return;
   }
  }
 }catch(e){
  if(detector&&typeof window.jsQR==='function'){
   detector=null;note('Переключено на локальный QR-декодер без отправки изображений.');
  }else note('Сканирование: '+(e.message||'ошибка камеры'));
 }
 if(active)timer=setTimeout(step,260);
}
async function start(){
 stop();note('Проверяю разрешение камеры…');
 if(!navigator.mediaDevices?.getUserMedia){
  note('Камера недоступна. Введи код товара вручную.');return;
 }
 try{
  detector=null;
  if('BarcodeDetector' in window)try{detector=new BarcodeDetector({formats:['qr_code']})}catch{}
  if(!detector&&typeof window.jsQR!=='function'){
   note('QR-декодер недоступен. Введи код вручную.');return;
  }
  stream=await navigator.mediaDevices.getUserMedia({video:{facingMode:{ideal:'environment'}},audio:false});
  if(!dialog.open){stop();return}
  active=true;video.srcObject=stream;
  await video.play();
  note('Камера включена. Наведи её на QR товара.');
  timer=setTimeout(step,100);
 }catch(e){
  stop();note('Камера недоступна: '+(e.message||'проверь разрешение')+'. Введи код вручную.');
 }
}
function open(){
 if(!dialog.open)dialog.showModal();
 void start();
}
$('pro-qr-close').onclick=close;
$('pro-qr-restart').onclick=()=>void start();
$('pro-qr-find').onclick=()=>select($('pro-qr-value').value);
$('pro-qr-value').addEventListener('keydown',e=>{if(e.key==='Enter'){e.preventDefault();select(e.currentTarget.value)}});
dialog.addEventListener('close',stop);
dialog.addEventListener('cancel',stop);
document.addEventListener('visibilitychange',()=>{if(document.hidden&&dialog.open){stop();note('Камера выключена. Для продолжения нажми «Включить камеру».')}});
function showCode(p){
 if(!p?.id||!p?.name)return;
 const wrapper=$('pro-qr-card'),box=$('pro-qr-art');
 if(!wrapper||!box||typeof window.qrcode!=='function')return;
 try{
  const qr=window.qrcode(0,'M');qr.addData('FP|'+p.id);qr.make();
  const svg=qr.createSvgTag(6,4);
  // Generated by the locally bundled MIT QR encoder; no network call.
  box.innerHTML=svg;
  $('pro-qr-product-name').textContent=p.name;
  $('pro-qr-product-id').textContent='Код: FP|'+p.id;
  $('pro-qr-download').onclick=()=>{
   const data='<?xml version="1.0" encoding="UTF-8"?>\n'+svg;
   const blob=new Blob([data],{type:'image/svg+xml;charset=utf-8'});
   const url=URL.createObjectURL(blob),a=document.createElement('a');
   a.href=url;a.download='QR-FARUKH-PRINT-'+p.id.replace(/[^a-z0-9-]/gi,'').slice(0,60)+'.svg';
   document.body.append(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),10000);
  };
  wrapper.showModal();
 }catch(e){note('Не удалось создать QR: '+e.message)}
}
$('pro-qr-card-close')?.addEventListener('click',()=>$('pro-qr-card').close());
window.FARUKH_PRINT_PRO_SCANNER={open,close,showCode};
})();
