'use strict';
const assert=require('node:assert/strict');
const {decimal,unit,parsePage}=require('./ocr-draft-parser');
const template={width:1000,height:1000,top:.1,bottom:.9,columns:{name:[0,.4],qty:[.4,.5],unit:[.5,.6],price:[.6,.8],amount:[.8,1]}};
const region=(text,x,y,score=.97)=>({text,score,box:[[x,y],[x+20,y],[x+20,y+8],[x,y+8]]});
const row=(y,q,p,a,u='кг',score=.97)=>[region('Тестовый товар',30,y),region(q,420,y),region(u,520,y),region(p,620,y),region(a,820,y,score)];
const r=parsePage([...row(200,'2,5','100,00','250,00'),...row(300,'3','100','299','шт',.7),...row(400,'2','100','200','??'),region('пересечение',395,500)],template);
assert.equal(decimal('1 234,50'),1234.5);
assert.equal(decimal('12O'),null);
assert.equal(unit('kг'),'кг');
assert.equal(r.rows.length,3);
assert.deepEqual(r.rows[0].flags,[]);
assert.ok(r.rows[1].flags.includes('arithmetic_mismatch'));
assert.equal(r.rows[1].factor,null);
assert.ok(r.rows[1].flags.includes('low_confidence:amount'));
assert.ok(r.rows[2].flags.includes('unknown_unit'));
assert.equal(r.unassigned.length,1);
assert.equal(r.complete,false);
assert.ok(r.rows.every(x=>x.requires_review));
console.log('12 checks passed (synthetic regions, not photo OCR)');
